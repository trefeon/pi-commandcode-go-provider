/**
 * Regenerates `src/generated-catalog.ts` from Command Code's public model
 * catalog, keeping only rows the Go plan can run.
 *
 * Usage: `bun run scripts/generate-catalog.ts` (add `--check` to fail when the
 * committed file is stale, as CI does).
 */

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { clampMaxTokens, MAX_OUTPUT_TOKENS } from "../src/protocol.js";

const CATALOG_URL = "https://api.commandcode.ai/provider/v1/models?view=client";
const GO_PLAN = "individual-go";
const OUTPUT_PATH = resolve(import.meta.dir, "../src/generated-catalog.ts");

const KNOWN_EFFORTS = ["off", "minimal", "low", "medium", "high", "xhigh", "max"] as const;

interface RawModel {
  id?: unknown;
  name?: unknown;
  hidden?: unknown;
  minimumPlan?: unknown;
  context_length?: unknown;
  maxOutputTokens?: unknown;
  inputModalities?: unknown;
  reasoningEfforts?: unknown;
  pricing?: { inputCost?: unknown; outputCost?: unknown; cacheReadCost?: unknown };
  display?: { label?: unknown };
}

interface GeneratedModel {
  id: string;
  wireId: string;
  name: string;
  contextWindow: number;
  maxTokens: number;
  reasoning: true;
  efforts?: string[];
  thinking?: { mode: "effort"; efforts: string[]; defaultLevel?: string };
  input: string[];
  toolCall: true;
  cost: { input: number; output: number; cacheRead: number; cacheWrite: number };
}

function bareId(wireId: string): string {
  const bare = wireId.includes("/") ? wireId.split("/").slice(1).join("/") : wireId;
  // Lowercase and `:free` → `-free`: CLI-friendly, filesystem-safe aliases.
  return bare.toLowerCase().replace(/:/g, "-");
}

function numberOr(value: unknown, fallback: number): number {
  return typeof value === "number" && Number.isFinite(value) && value > 0 ? value : fallback;
}

function rate(value: unknown): number {
  return typeof value === "number" && Number.isFinite(value) && value >= 0 ? value : 0;
}

function toModel(raw: RawModel): GeneratedModel | undefined {
  if (typeof raw.id !== "string" || raw.id.trim().length === 0) return undefined;
  if (raw.hidden === true || raw.minimumPlan !== GO_PLAN) return undefined;

  const wireId = raw.id.trim();
  const efforts = Array.isArray(raw.reasoningEfforts)
    ? [...new Set(
        raw.reasoningEfforts
          .filter((level): level is string => typeof level === "string")
          .map((level) => level.trim().toLowerCase())
          .filter((level) => (KNOWN_EFFORTS as readonly string[]).includes(level)),
      )]
    : [];
  const modalities = Array.isArray(raw.inputModalities)
    ? raw.inputModalities.filter((m): m is string => m === "text" || m === "image")
    : [];
  const declaredMax = numberOr(raw.maxOutputTokens, MAX_OUTPUT_TOKENS);
  const defaultLevel = efforts.includes("high") ? "high" : efforts.find((level) => level !== "off");
  const label =
    typeof raw.display?.label === "string"
      ? raw.display.label
      : typeof raw.name === "string"
        ? raw.name
        : bareId(wireId);

  return {
    id: bareId(wireId),
    wireId,
    name: label,
    contextWindow: numberOr(raw.context_length, 1_000_000),
    maxTokens: clampMaxTokens(declaredMax),
    reasoning: true,
    ...(efforts.length > 0
      ? { efforts, thinking: { mode: "effort" as const, efforts, defaultLevel } }
      : {}),
    input: modalities.length > 0 ? modalities : ["text"],
    toolCall: true,
    cost: {
      input: rate(raw.pricing?.inputCost),
      output: rate(raw.pricing?.outputCost),
      cacheRead: rate(raw.pricing?.cacheReadCost),
      cacheWrite: 0,
    },
  };
}

function render(models: GeneratedModel[]): string {
  const body = models
    .map((model) => `  ${JSON.stringify(model)},`)
    .join("\n");
  return `/**
 * Generated by scripts/generate-catalog.ts — do not edit by hand.
 * Source: ${CATALOG_URL}
 * Go-plan rows only (minimumPlan=${GO_PLAN}, visible, max_tokens <= ${MAX_OUTPUT_TOKENS}).
 */
import type { CommandCodeGoModel } from "./types.js";

export const GENERATED_MODELS: CommandCodeGoModel[] = [
${body}
];
`;
}

async function main(): Promise<void> {
  const checkOnly = process.argv.includes("--check");
  const res = await fetch(CATALOG_URL, {
    headers: { accept: "application/json", "user-agent": "cli" },
    signal: AbortSignal.timeout(20_000),
  });
  if (!res.ok) throw new Error(`catalog fetch failed: HTTP ${res.status}`);

  const payload: unknown = await res.json();
  if (!payload || typeof payload !== "object" || !Array.isArray((payload as { data?: unknown }).data)) {
    throw new Error("catalog payload has no data array");
  }

  const rows = (payload as { data: RawModel[] }).data;
  const models: GeneratedModel[] = [];
  const seen = new Set<string>();
  for (const raw of rows) {
    const model = toModel(raw);
    if (!model || seen.has(model.id)) continue;
    seen.add(model.id);
    models.push(model);
  }
  if (models.length === 0) throw new Error("catalog produced no Go-plan models");

  const rendered = render(models);
  if (checkOnly) {
    const current = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, "utf-8") : "";
    if (current !== rendered) {
      console.error(`[generate-catalog] ${OUTPUT_PATH} is stale; run bun run scripts/generate-catalog.ts`);
      process.exit(1);
    }
    console.log(`[generate-catalog] up to date (${models.length} Go models)`);
    return;
  }

  writeFileSync(OUTPUT_PATH, rendered, "utf-8");
  console.log(`[generate-catalog] wrote ${models.length} Go models to ${OUTPUT_PATH}`);
}

main().catch((err: unknown) => {
  console.error("[generate-catalog]", err instanceof Error ? err.message : err);
  process.exit(1);
});
